// Rasterizes Natural Earth land (world-atlas, 1:50m) into the game's fixed equirectangular grid
// and writes it as a run-length encoded module. Run: node scripts/build-earth.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const WIDTH = 2048;
const HEIGHT = 832;
const DEG_PER_PX = 360 / WIDTH;
const TOP_LAT = 84;

const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);

const rings = [];
for (const item of land.features ?? [land]) {
  const geometry = item.geometry;
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) for (const ring of polygon) rings.push(ring);
}

// Scanline even-odd fill at pixel centres, with every polygon ring contributing crossings.
const mask = new Uint8Array(WIDTH * HEIGHT);
const crossings = Array.from({ length: HEIGHT }, () => []);
let skippedPolar = 0;
for (const raw of rings) {
  // Unwrap longitudes so rings crossing the antimeridian stay continuous, then draw shifted copies.
  const ring = [];
  let offset = 0;
  for (let i = 0; i < raw.length; i += 1) {
    if (i > 0) {
      const jump = raw[i][0] - raw[i - 1][0];
      if (jump > 180) offset -= 360;
      if (jump < -180) offset += 360;
    }
    ring.push([raw[i][0] + offset, raw[i][1]]);
  }
  if (Math.abs(ring[ring.length - 1][0] - ring[0][0]) > 180) {
    skippedPolar += 1; // encircles a pole (Antarctica) — lies outside the cropped latitudes
    continue;
  }
  for (const shift of [-360, 0, 360]) {
    for (let i = 0; i < ring.length - 1; i += 1) {
      const [lon0, lat0] = ring[i];
      const [lon1, lat1] = ring[i + 1];
      const x0 = (lon0 + shift + 180) / DEG_PER_PX;
      const y0 = (TOP_LAT - lat0) / DEG_PER_PX;
      const x1 = (lon1 + shift + 180) / DEG_PER_PX;
      const y1 = (TOP_LAT - lat1) / DEG_PER_PX;
      if (y0 === y1) continue;
      const yMin = Math.min(y0, y1);
      const yMax = Math.max(y0, y1);
      const rowStart = Math.max(0, Math.ceil(yMin - 0.5));
      const rowEnd = Math.min(HEIGHT - 1, Math.floor(yMax - 0.5));
      for (let row = rowStart; row <= rowEnd; row += 1) {
        const yc = row + 0.5;
        if (yc < yMin || yc >= yMax) continue;
        crossings[row].push(x0 + ((yc - y0) / (y1 - y0)) * (x1 - x0));
      }
    }
  }
}
for (let row = 0; row < HEIGHT; row += 1) {
  const xs = crossings[row].sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const from = Math.max(0, Math.ceil(xs[k] - 0.5));
    const to = Math.min(WIDTH - 1, Math.floor(xs[k + 1] - 0.5));
    for (let x = from; x <= to; x += 1) mask[row * WIDTH + x] = 1;
  }
}

// Run-length encode (alternating water/land runs, starting with water) as LEB128 varints.
const bytes = [];
const pushVarint = (value) => {
  let v = value;
  while (v >= 0x80) {
    bytes.push((v & 0x7f) | 0x80);
    v >>>= 7;
  }
  bytes.push(v);
};
let current = 0;
let run = 0;
for (let i = 0; i < mask.length; i += 1) {
  if (mask[i] === current) {
    run += 1;
  } else {
    pushVarint(run);
    current = mask[i];
    run = 1;
  }
}
pushVarint(run);

const landCount = mask.reduce((sum, value) => sum + value, 0);
const base64 = Buffer.from(bytes).toString('base64');
const out = path.resolve(import.meta.dirname, '../src/game/data/earthLand.ts');
writeFileSync(
  out,
  `// Generated by scripts/build-earth.mjs from Natural Earth 1:50m land (public domain). Do not edit.\n` +
    `export const EARTH_WIDTH = ${WIDTH};\nexport const EARTH_HEIGHT = ${HEIGHT};\n` +
    `export const EARTH_TOP_LAT = ${TOP_LAT};\nexport const EARTH_DEG_PER_PX = ${DEG_PER_PX};\n` +
    `export const EARTH_LAND_RLE = '${base64}';\n`,
);

// Preview image for manual checking.
const pgm = Buffer.concat([Buffer.from(`P5 ${WIDTH} ${HEIGHT} 255\n`), Buffer.from(mask.map((v) => (v ? 60 : 230)))]);
writeFileSync('/tmp/earth-preview.pgm', pgm);
console.log(`polar rings skipped ${skippedPolar}; land pixels ${landCount} of ${mask.length}; encoded ${bytes.length} bytes`);
